mround <- function(x, digits) {
  sprintf(paste0("%.", digits, "f"), round(x, digits))
}

write_tex_comment <- function(comment) {
  paste0("% ", comment) |>
    readr::write_lines(here("text", "values.tex"), append = TRUE)
}

write_tex <- function(x, macro) {
  paste0("\\newcommand{\\", macro, "}{", x, "}") |>
    readr::write_lines(here("text", "values.tex"), append = TRUE)
}

