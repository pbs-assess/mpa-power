# Macro names: letters only (LaTeX multiletter names); no underscores; must not
# start with digits; avoid macros starting with `n` + letter (e.g. use Num* not
# n*) because `\n` is a TeX newline command.
path_hbll_sites <- here("data-generated", "overlays", "hbll-site-summary-table.rds")
path_fit_char <- fit_characteristics_file
path_power_df <- here("data-generated", "power-df-historical-sampling.rds")

if (all(file.exists(c(path_hbll_sites, path_fit_char, path_power_df)))) {
  write_tex_comment("\n% Power analysis values")
  write_tex_comment("-------------------")

  hbll_sites_all <- readRDS(path_hbll_sites)
  hbll_n_sites_unique <- length(unique(hbll_sites_all$`Common Site Name`))
  write_tex(as.character(hbll_n_sites_unique), "NumHbllProtectedSites")

  mean_fit_values <- readRDS(path_fit_char) |>
    filter(
      (species %in% c("canary rockfish", "silvergray rockfish") & survey %in% c("HBLL OUT N", "HBLL OUT S")) |
        !(species %in% c("canary rockfish", "silvergray rockfish"))
    ) |>
    group_by(species) |>
    summarise(across(encountered_count_per_year:sigma_E, mean))

  canary_encounter <- mean_fit_values |>
    filter(species == "canary rockfish") |>
    pull(encountered_rate_restricted)
  silvergray_encounter <- mean_fit_values |>
    filter(species == "silvergray rockfish") |>
    pull(encountered_rate_restricted)
  dogfish_encounter <- mean_fit_values |>
    filter(species == "north pacific spiny dogfish") |>
    pull(encountered_rate_restricted)

  write_tex(as.character(round(canary_encounter * 100, 0)), "CanaryEncounterRatePct")
  write_tex(as.character(round(silvergray_encounter * 100, 0)), "SilvergrayEncounterRatePct")
  write_tex(as.character(round(dogfish_encounter * 100, 0)), "DogfishEncounterRatePct")

  power_df <- readRDS(path_power_df)
  power_wide <- power_df |>
    select(species, mpa_effect_label, eval_year, power_signed) |>
    tidyr::pivot_wider(names_from = "eval_year", values_from = "power_signed")

  fmt_power_row <- function(pw) {
    pw |>
      mutate(across(where(is.numeric), \(x) sprintf("%.2f", round(x, 2))))
  }

  qb_25_power <- power_wide |>
    filter(species == "quillback rockfish", mpa_effect_label == "25%") |>
    fmt_power_row()
  ling_25_power <- power_wide |>
    filter(species == "lingcod", mpa_effect_label == "25%") |>
    fmt_power_row()
  ye_25_power <- power_wide |>
    filter(species == "yelloweye rockfish", mpa_effect_label == "25%") |>
    fmt_power_row()

  write_tex(pull(qb_25_power, "2046"), "PowerQbTwentyfiveTwentyFourtySix")
  write_tex(pull(ling_25_power, "2046"), "PowerLcTwentyfiveTwentyFourtySix")
  write_tex(pull(ye_25_power, "2046"), "PowerYeTwentyfiveTwentyFourtySix")
} else {
  write_tex_comment("\n% Power analysis skipped (HBLL overlay, fit_characteristics, or power RDS missing)")
}
